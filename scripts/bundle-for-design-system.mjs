// Bundles LearnKit and one brand theme for a Claude Design "Design System".
//   node scripts/bundle-for-design-system.mjs --theme blc [--out dist]
//   npm run bundle -- --theme howdigital
//   add --card to write a ready-to-publish components/LearnKit folder instead
//   (learnkit.js, learnkit.css, preview.html, README.md) under <out>/<theme>/.
//
// Writes <out>/learnkit-<theme>.js and <out>/learnkit-<theme>.css.
// The script is a classic script (no import statements, no network) that
// assigns window.LearnKit and registers every component. The stylesheet is
// learnkit.css followed by the theme. This is for export only: LearnKit itself
// stays no-build and dependency-free.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve, relative } from 'node:path';
import { card } from './design-system-card.mjs';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = resolve(ROOT, 'src');
export const THEMES = ['blc', 'howdigital'];

const IMPORT_FROM = /^import\s*\{([^}]*)\}\s*from\s*'([^']+)';?[ \t]*\n/gm;
const IMPORT_SIDE = /^import\s*'([^']+)';?[ \t]*\n/gm;
const REEXPORT = /^export\s*\{([^}]*)\}\s*from\s*'([^']+)';?[ \t]*\n/gm;
const EXPORT_DECL = /^export\s+(class|function|const)\s+([A-Za-z_$][\w$]*)/gm;
const EXPORT_LIST = /^export\s*\{([^}]*)\};?[ \t]*\n/gm;

const names = (list) => list.split(',').map((s) => s.trim()).filter(Boolean);
const ident = (file) => 'm_' + relative(SRC, file).replace(/\.js$/, '').replace(/[^\w]/g, '_');

/** Reads one module and returns its dependencies and a function-wrapped body. */
function transform(file, order, seen) {
  if (seen.has(file)) return;
  seen.add(file);
  let code = readFileSync(file, 'utf8');
  const deps = [];
  const dep = (spec) => {
    const path = resolve(dirname(file), spec);
    deps.push(path);
    return path;
  };

  const lines = [];
  code = code.replace(IMPORT_FROM, (_, list, spec) => {
    const path = dep(spec);
    const pairs = names(list).map((n) => n.replace(/\s+as\s+/, ': '));
    lines.push(`const { ${pairs.join(', ')} } = ${ident(path)};`);
    return '';
  });
  code = code.replace(IMPORT_SIDE, (_, spec) => { dep(spec); return ''; });

  const exported = [];
  code = code.replace(EXPORT_DECL, (_, kind, name) => { exported.push(name); return `${kind} ${name}`; });
  code = code.replace(EXPORT_LIST, (_, list) => { exported.push(...names(list)); return ''; });
  const reexports = [];
  code = code.replace(REEXPORT, (_, list, spec) => {
    const path = dep(spec);
    for (const n of names(list)) reexports.push([n, path]);
    return '';
  });
  if (/^(import|export)\s*(\{|\*|'|"|default\b|[\w$]+\s+from)/m.test(code.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, ''))) {
    throw new Error(`${relative(ROOT, file)}: import/export form the bundler does not understand`);
  }

  for (const d of deps) transform(d, order, seen);

  const out = [...exported, ...reexports.map(([n]) => n)];
  const reexportLines = reexports.map(([n, p]) => `const ${n} = ${ident(p)}.${n};`);
  order.push(
    `/* ${relative(SRC, file)} */\n` +
    `const ${ident(file)} = (() => {\n${[...lines, code.trim(), ...reexportLines].join('\n')}\n` +
    `return { ${out.join(', ')} };\n})();\n`,
  );
  return reexports.map(([n, p]) => [n, p]);
}

export function bundle(theme) {
  if (!THEMES.includes(theme)) throw new Error(`theme must be one of ${THEMES.join(', ')}`);
  const version = JSON.parse(readFileSync(resolve(ROOT, 'package.json'), 'utf8')).version;
  const order = [];
  transform(resolve(SRC, 'index.js'), order, new Set());

  const banner = `/* LearnKit ${version}, ${theme} theme. Generated by scripts/bundle-for-design-system.mjs. Do not edit. */`;
  let js = `${banner}\n(function () {\n'use strict';\n${order.join('\n')}\nwindow.LearnKit = Object.assign({ version: ${JSON.stringify(version)}, theme: ${JSON.stringify(theme)} }, ${ident(resolve(SRC, 'index.js'))});\n})();\n`;
  // Safe inside an inline <script>: these only ever appear in comments or strings.
  js = js.replace(/<\/script/gi, '<\\/script').replace(/<!--/g, '<\\!--');

  const css = `${banner}\n` +
    readFileSync(resolve(SRC, 'learnkit.css'), 'utf8') + '\n' +
    readFileSync(resolve(SRC, 'themes', `${theme}.css`), 'utf8');
  return { js, css, version };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const arg = (flag, fallback) => {
    const i = process.argv.indexOf(flag);
    return i > -1 ? process.argv[i + 1] : fallback;
  };
  const theme = arg('--theme');
  const out = resolve(ROOT, arg('--out', 'dist'));
  if (!theme) { console.error(`Usage: --theme <${THEMES.join('|')}> [--out dir]`); process.exit(1); }
  const { js, css, version } = bundle(theme);
  if (process.argv.includes('--card')) {
    const dir = resolve(out, theme, 'project/components/LearnKit');
    mkdirSync(dir, { recursive: true });
    const files = { 'learnkit.js': js, 'learnkit.css': css, ...card(theme, version) };
    for (const [name, text] of Object.entries(files)) writeFileSync(resolve(dir, name), text);
    console.log(`LearnKit ${version} (${theme}) card -> ${relative(process.cwd(), dir)}`);
    process.exit(0);
  }
  mkdirSync(out, { recursive: true });
  writeFileSync(resolve(out, `learnkit-${theme}.js`), js);
  writeFileSync(resolve(out, `learnkit-${theme}.css`), css);
  console.log(`LearnKit ${version} (${theme}): ${(js.length / 1024).toFixed(0)} KB js, ${(css.length / 1024).toFixed(0)} KB css -> ${relative(process.cwd(), out) || '.'}`);
}
